#!/usr/bin/env bun
/**
 * generate-worktree-constants.ts
 *
 * Codegen step: regenerate `scripts/lib/worktree-constants.sh` from the
 * TypeScript constants in `shared/src/worktreeMeta.ts`.
 *
 * Wired into `bun run build:single-exe` and runnable standalone via
 * `bun run gen:worktree-constants`. The output file is gitignored — bash
 * scripts source it via `scripts/lib/regen-constants.sh`, which regenerates
 * if missing.
 *
 * See: issue #1144 for context.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  WORKTREE_PORT_MAX,
  WORKTREE_PORT_MIN,
} from "../shared/src/worktreeMeta";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "..");
const outDir = join(repoRoot, "scripts", "lib");
const outFile = join(outDir, "worktree-constants.sh");

mkdirSync(outDir, { recursive: true });

const content = [
  "# Auto-generated by scripts/generate-worktree-constants.ts — do not edit.",
  "# Source of truth: shared/src/worktreeMeta.ts",
  "# Regenerate: bun run gen:worktree-constants",
  `export WORKTREE_PORT_MIN=${WORKTREE_PORT_MIN}`,
  `export WORKTREE_PORT_MAX=${WORKTREE_PORT_MAX}`,
  "",
].join("\n");

writeFileSync(outFile, content);
console.log(`Wrote ${outFile}`);
console.log(`  WORKTREE_PORT_MIN=${WORKTREE_PORT_MIN}`);
console.log(`  WORKTREE_PORT_MAX=${WORKTREE_PORT_MAX}`);
