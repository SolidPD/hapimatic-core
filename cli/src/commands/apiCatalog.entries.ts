/**
 * Capability catalog — `cli` surface entries (issue #3745, epic #3740, Sub-Issue E).
 *
 * One `defineCapability({ surface: "cli", invocation: { kind: "cli", command } })`
 * literal per observed CLI item. #3744's `buildLocalSurface` observes the cli
 * roster as `[...listCommands(), "claude"]` PLUS every `api <resource> <action>`
 * pair from `API_RESOURCE_ACTIONS`, and the audit matches `invocation.command`
 * against those exact strings (a bare command name, or `api <resource> <action>`,
 * or `api <resource>` for an actionless resource).
 *
 * ⚠️ `claude` IS catalogued (correcting the directive's R8): `buildLocalSurface`
 * appends `"claude"` to the observed roster and the audit's reverse-drift loop
 * has NO `claude` exclusion, so a `claude` entry RESOLVES (in-roster) and its
 * ABSENCE is reverse-drift. R8 conflated `listCommands()` (which excludes the
 * implicit-default `claude`) with the observed roster (which includes it). Per
 * R8's own "code wins" rule + R9's zero-reverse-drift gate, `claude` is an entry.
 *
 * The 15 static groups + `capabilities` (from #3744) are `listCommands()`; the
 * extension-contributed `codex` + `gemini` (registered at load via
 * `host.commands.add`) join the RUNTIME roster; `api` is both a command group AND
 * the parent of the api-pair entries. Pure object literals only (#3743); text
 * respects #3741's caps (description ≤ 200, whenToUse ≤ 160).
 */
