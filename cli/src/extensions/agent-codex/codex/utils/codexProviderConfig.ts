/**
 * Issue #1733 — Codex provider-config emission for OpenRouter (and other
 * OpenAI-compatible gateways), reached by reusing the shipped Codex launcher
 * rather than building a new harness.
 *
 * Emits a per-session `config.toml` that points Codex at OpenRouter via a
 * `[model_providers.openrouter]` table. The OpenRouter API key is delivered
 * out-of-band via the `OPENROUTER_API_KEY` environment variable (Codex's
 * `env_key` mechanism), NOT written into this file — so no plaintext key ever
 * lands on disk (stronger than the directive's optional inline-token path; see
 * KD-2/R3/R9). Codex's `[shell_environment_policy]` default secret-drop plus
 * the explicit `exclude` here keep the key out of the agent's bash-tool
 * subprocess environment.
 *
 * Never overrides the built-in `openai` provider — Codex ignores overrides on
 * built-ins; the uniquely-named `openrouter` block is always used (KD-5).
 */
import { writeFile, chmod } from "node:fs/promises";
import { join } from "node:path";
import {
  serializeCodexMcpServersToml,
  type CodexMcpServersSection,
} from "@/agent/projection/mcp/codex";

/** Base URL for the OpenRouter OpenAI-compatible gateway. */
export const OPENROUTER_BASE_URL = "https://openrouter.ai/api/v1";

/** Env var Codex reads the OpenRouter key from (set by the daemon at spawn). */
export const OPENROUTER_ENV_KEY = "OPENROUTER_API_KEY";

/** Escape a string for use inside a TOML basic (double-quoted) string. */
function escapeTomlString(value: string): string {
  return value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r")
    .replace(/\t/g, "\\t");
}

/**
 * Build the body of a Codex `config.toml` that routes the session through
 * OpenRouter for `args.model`. The key is NOT embedded — it is delivered via
 * `env_key` (see module docstring), so this file is safe to write even though
 * it is mode 0600 by convention.
 */
export function buildOpenRouterCodexConfigToml(args: {
  model: string;
}): string {
  const model = escapeTomlString(args.model);
  return [
    "# Generated by Hapimatic (issue #1733) — OpenRouter provider for Codex.",
    "# The OpenRouter API key is delivered via the OPENROUTER_API_KEY env var",
    "# (env_key) and is NEVER written to this file. shell_environment_policy",
    "# excludes it from the agent's bash-tool subprocess environment.",
    "",
    `model_provider = "openrouter"`,
    `model = "${model}"`,
    "",
    "[model_providers.openrouter]",
    `name = "OpenRouter"`,
    `base_url = "${OPENROUTER_BASE_URL}"`,
    `wire_api = "responses"`,
    `env_key = "${OPENROUTER_ENV_KEY}"`,
    "",
    "[shell_environment_policy]",
    `exclude = ["${OPENROUTER_ENV_KEY}"]`,
    "",
  ].join("\n");
}

/**
 * Build the COMPOSED codex `config.toml` (issue #3125, KD1): the OpenRouter
 * provider tables PLUS an optional `[mcp_servers]` section from the HAL canonical
 * MCP set. This is the SINGLE `config.toml` builder — a second independent writer
 * of the same file would clobber whichever ran second (losing provider routing
 * or all MCP), so the MCP section is threaded in here rather than written
 * separately (V6). The `[mcp_servers]` fragment is serialized with `smol-toml`
 * (correct key/value quoting for arbitrary server names + args), while the
 * provider section keeps its validated hand-built form (its only variable, the
 * model id, is already escaped). Absent/empty `mcpServers` → byte-identical to
 * the provider-only output (backward compatible with the pre-#3125 call sites).
 */
export function buildComposedCodexConfigToml(args: {
  model: string;
  mcpServers?: CodexMcpServersSection;
}): string {
  const providerToml = buildOpenRouterCodexConfigToml({ model: args.model });
  const mcpFragment =
    args.mcpServers && Object.keys(args.mcpServers).length > 0
      ? serializeCodexMcpServersToml(args.mcpServers)
      : "";
  if (!mcpFragment) return providerToml;
  return `${providerToml.trimEnd()}\n\n${mcpFragment.trimEnd()}\n`;
}

/**
 * Write the composed OpenRouter `config.toml` into a per-session `CODEX_HOME`
 * directory with mode 0600 (R9; #3125 R2 for the MCP `env` maps it now carries).
 * The directory must already exist (the daemon `mkdtemp`s it). chmod-after-write
 * is a umask-defense (accountStore.ts precedent). `mcpServers` is optional — when
 * omitted the output is byte-identical to the provider-only config.
 */
export async function writeOpenRouterCodexHome(
  codexHome: string,
  args: { model: string; mcpServers?: CodexMcpServersSection }
): Promise<void> {
  const target = join(codexHome, "config.toml");
  await writeFile(target, buildComposedCodexConfigToml(args), {
    mode: 0o600,
  });
  await chmod(target, 0o600).catch(() => {});
}

/**
 * Issue #3348 — build a ChatGPT-AUTH codex `config.toml` (NOT the OpenRouter
 * path). The ChatGPT-token codex path authenticates via `auth.json` (the OAuth
 * token) and uses codex's built-in `openai` provider, so this config carries NO
 * `[model_providers.*]` table — only the selected `model` and (when set) the
 * `model_reasoning_effort`, exactly the `-c model=…` / `-c model_reasoning_effort=…`
 * overrides codex accepts. An optional `[mcp_servers]` section is threaded in the
 * SAME builder (mirrors {@link buildComposedCodexConfigToml}) so a second writer
 * cannot clobber this file. With no model, no effort, and no MCP, this returns an
 * empty-body comment — the caller only writes it when at least one is set, so a
 * model-less/effort-less codex session's config is never materialized (R7 —
 * byte-identical to today).
 */
export function buildChatGptCodexConfigToml(args: {
  model?: string;
  reasoningEffort?: string;
  mcpServers?: CodexMcpServersSection;
}): string {
  const lines: string[] = [
    "# Generated by Hapimatic (issue #3348) — ChatGPT-auth Codex model/effort.",
    "# ChatGPT auth is delivered via auth.json (the OAuth token); this file only",
    "# overrides the model + reasoning effort (codex's built-in openai provider).",
    "",
  ];
  if (args.model) {
    lines.push(`model = "${escapeTomlString(args.model)}"`);
  }
  if (args.reasoningEffort) {
    lines.push(
      `model_reasoning_effort = "${escapeTomlString(args.reasoningEffort)}"`
    );
  }
  lines.push("");
  const base = lines.join("\n");
  const mcpFragment =
    args.mcpServers && Object.keys(args.mcpServers).length > 0
      ? serializeCodexMcpServersToml(args.mcpServers)
      : "";
  if (!mcpFragment) return base;
  return `${base.trimEnd()}\n\n${mcpFragment.trimEnd()}\n`;
}

/**
 * Write the ChatGPT-auth `config.toml` into a per-session `CODEX_HOME` with mode
 * 0600 (mirrors {@link writeOpenRouterCodexHome}). The directory must already
 * exist. `mcpServers` optional. This coexists with the auth.json the daemon writes
 * for the ChatGPT OAuth token — codex reads both from the same CODEX_HOME.
 */
export async function writeChatGptCodexHome(
  codexHome: string,
  args: {
    model?: string;
    reasoningEffort?: string;
    mcpServers?: CodexMcpServersSection;
  }
): Promise<void> {
  const target = join(codexHome, "config.toml");
  await writeFile(target, buildChatGptCodexConfigToml(args), { mode: 0o600 });
  await chmod(target, 0o600).catch(() => {});
}
