/**
 * OpenCode JS plugin-shim emitter (issue #3123, Task 5 / KD4).
 *
 * OpenCode has NO native lifecycle-hook taxonomy — hooks are a JS plugin. This
 * emitter generates a deterministic OpenCode plugin exporting
 * `tool.execute.before` / `tool.execute.after` that shells out to the SAME
 * CLI-neutral guard command(s) as the native dialects (R4). Its manifest hooks
 * axis is `plugin-shim`, so its coverage records carry `native: false` (KD6).
 *
 * Only `PreToolUse` → `tool.execute.before` and `PostToolUse` →
 * `tool.execute.after` map onto OpenCode's tool-execution surface; the other
 * Claude events have no OpenCode equivalent and degrade at the transpiler level
 * (R3), never silently dropped.
 */
import type { CanonicalHook, DialectFile, HookEvent } from "../transpiler";

/** The Claude events the OpenCode `tool.execute.*` surface can represent. */
export const OPENCODE_SUPPORTED_EVENTS: ReadonlySet<HookEvent> = new Set([
  "PreToolUse",
  "PostToolUse",
]);

/** Config-home-relative path of the generated OpenCode plugin. */
export const OPENCODE_PLUGIN_PATH = ".opencode/plugin/hal-hooks.js";

/** The embedded per-hook record the generated plugin dispatches on. */
interface ShimHookRecord {
  event: "PreToolUse" | "PostToolUse";
  matcher: string;
  command: string;
  timeout?: number;
}

/**
 * Emit the OpenCode plugin-shim. `projectable` is already filtered to
 * `PreToolUse` / `PostToolUse` by the transpiler. The command strings are
 * embedded verbatim (R4). The generated JS is minimal and dependency-free
 * (`node:child_process`) so it loads deterministically.
 */
export function emitOpencodeShim(projectable: CanonicalHook[]): DialectFile {
  const records: ShimHookRecord[] = projectable
    .filter(
      (h): h is CanonicalHook & { event: "PreToolUse" | "PostToolUse" } =>
        h.event === "PreToolUse" || h.event === "PostToolUse"
    )
    .map(h => {
      const rec: ShimHookRecord = {
        event: h.event,
        matcher: h.matcher,
        command: h.command,
      };
      if (h.timeout !== undefined) {
        rec.timeout = h.timeout;
      }
      return rec;
    });

  const content = `// Generated by HAL hook projection (hapimatic-private #3123) — DO NOT EDIT.
// OpenCode has no native hook taxonomy; this plugin-shim invokes the SAME
// CLI-neutral guard command(s) as every other dialect (R4) via tool.execute.*.
import { spawnSync } from "node:child_process";

/** Projected canonical hooks (PreToolUse -> before, PostToolUse -> after). */
const HAL_HOOKS = ${JSON.stringify(records, null, 2)};

function runHalPhase(event, toolName) {
  for (const hook of HAL_HOOKS) {
    if (hook.event !== event) continue;
    if (hook.matcher && hook.matcher !== "*" && hook.matcher !== toolName) {
      continue;
    }
    spawnSync(hook.command, {
      shell: true,
      stdio: "inherit",
      timeout: hook.timeout,
    });
  }
}

export const HalHooksPlugin = async () => ({
  "tool.execute.before": async input => {
    runHalPhase("PreToolUse", input?.tool);
  },
  "tool.execute.after": async input => {
    runHalPhase("PostToolUse", input?.tool);
  },
});
`;

  return { path: OPENCODE_PLUGIN_PATH, content };
}
