/**
 * `ui/icons` — a small set of stateless inline-SVG glyph components (Copy, Check,
 * Trash, Maximize, Minimize, PopOut, Close), extracted from SessionNotes.tsx for
 * reuse. Contract: `docs/design/design-system/primitives.md`.
 *
 * - **Naming**: the copy/check glyphs export as `UiCopyIcon` / `UiCheckIcon` (not
 *   `CopyIcon` / `CheckIcon`) to avoid a same-name collision with the canonical
 *   `@/components/icons`, whose `CopyIcon`/`CheckIcon` render DIFFERENT geometry —
 *   importing the wrong same-named symbol silently shifts pixels (#3540, R4). The
 *   other glyphs keep their bare names (no canonical collision that mixes glyphs).
 *
 * - **Anatomy**: each is a 24×24 `<svg>` using `stroke="currentColor"`, so it
 *   inherits the parent's text color.
 * - **Props / API**: `{ className?: string }` only — size via `h-N w-N`, color via
 *   the parent's `text-*`.
 * - **Variants / sizes / states**: none — pure presentation.
 * - **A11y**: decorative (no `<title>`/role). The CONSUMING control (button/link)
 *   owns the accessible name via `aria-label`; an icon must not be the sole label.
 * - **Tokens**: none directly — color inherited from the caller's `text-*` token.
 */

