#!/usr/bin/env bun
/**
 * generate-iso4217-currencies-v1 (issue #6779, P-1, P-2).
 *
 * Writes `shared/src/iso4217/currencies.generated.ts` (code to exponent) and
 * `shared/src/iso4217/currencies.provenance.json` from a copy of ISO 4217's
 * list one fetched from the maintenance agency:
 *
 *   bun run shared/scripts/generate-iso4217-currencies-v1.ts <path of the fetched file>
 *
 * The fetched file is kept outside the repository: the publisher's terms for
 * redistributing it have not been read, so only the table, this generator and
 * the provenance record are committed. The generator merges the fresh list into
 * the committed table and never deletes a row (a code is never removed once
 * released), and fails when the source changes the exponent of a held code.
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import {
  mergeIntoCommittedTable,
  parseListOne,
  selectBillingCurrencies,
} from "../src/iso4217/parseListOne";

const VERSION = "generate-iso4217-currencies-v1";
const SOURCE_URL =
  "https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "../src/iso4217");
const tablePath = join(outDir, "currencies.generated.ts");
const provenancePath = join(outDir, "currencies.provenance.json");

async function readCommittedTable(): Promise<Record<string, number>> {
  if (!existsSync(tablePath)) return {};
  const mod = (await import(tablePath)) as {
    ISO4217_CURRENCY_EXPONENTS: Record<string, number>;
  };
  return { ...mod.ISO4217_CURRENCY_EXPONENTS };
}

function renderTable(table: Record<string, number>, published: string): string {
  const lines = Object.entries(table).map(
    ([code, exponent]) => `  ${code}: ${exponent},`
  );
  return [
    `// GENERATED by shared/scripts/${VERSION}.ts from ISO 4217 list one`,
    `// (published ${published}). Do not edit by hand: regenerate, and read the`,
    "// provenance record beside this file, ./currencies.provenance.json.",
    "// A held code is never removed and its exponent never changes (#6779, P-2).",
    "export const ISO4217_CURRENCY_EXPONENTS: Readonly<Record<string, number>> =",
    "  Object.freeze({",
    ...lines.map(line => `  ${line}`),
    "  });",
    "",
  ].join("\n");
}

async function main(): Promise<void> {
  console.log(`[${VERSION}]`);
  const sourcePath = process.argv[2];
  if (!sourcePath) {
    console.error(`usage: bun run shared/scripts/${VERSION}.ts <list-one.xml>`);
    process.exit(2);
  }
  const bytes = readFileSync(sourcePath);
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  const list = parseListOne(bytes.toString("utf8"));
  if (!list.published) throw new Error("the file carries no Pblshd date");
  const selection = selectBillingCurrencies(list);
  const committed = await readCommittedTable();
  const { table, retainedNotInSource } = mergeIntoCommittedTable(
    committed,
    selection.kept
  );
  const exponentCounts: Record<string, number> = {};
  for (const exponent of Object.values(table)) {
    exponentCounts[exponent] = (exponentCounts[exponent] ?? 0) + 1;
  }
  const provenance = {
    publisher:
      "SIX Financial Information AG, the maintenance agency of ISO 4217",
    list: "ISO 4217 list one (current currency and funds)",
    fetchedFrom: SOURCE_URL,
    published: list.published,
    sha256,
    entriesRead: list.entries.length,
    codeCount: Object.keys(table).length,
    exponentCounts,
    rawFileCommitted: false,
    rawFileNote:
      "The fetched file is not committed: the publisher's terms for redistributing it were not read (#6779, P-1 as refined 2026-11-19).",
    generator: `shared/scripts/${VERSION}.ts`,
    dropRules: [
      'funds: entries whose CcyNm carries IsFund="true"',
      "metals: XAU, XAG, XPD, XPT (minor unit N.A.)",
      "the test code XTS and the no-currency code XXX (minor unit N.A.)",
      "every other entry whose minor unit is not a number (N.A.)",
      "entries with no code",
      "withdrawn codes the table never held (list one carries current codes only; list three is not read)",
      "a code the table already holds is never dropped; retainedNotInSource lists any the source no longer carries",
    ],
    dropped: selection.dropped,
    retainedNotInSource,
  };
  writeFileSync(tablePath, renderTable(table, list.published));
  // The record is not a `*.generated.*` file, so it is written in Prettier's
  // style: a regeneration of the same list leaves it byte for byte unchanged.
  const prettierOptions = (await resolveConfig(provenancePath)) ?? {};
  writeFileSync(
    provenancePath,
    await format(JSON.stringify(provenance, null, 2), {
      ...prettierOptions,
      filepath: provenancePath,
    })
  );
  console.log(
    `published ${list.published}, sha256 ${sha256}, ${provenance.codeCount} codes kept ${JSON.stringify(exponentCounts)}`
  );
}

await main();
