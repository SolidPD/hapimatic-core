import { z } from "zod";

/**
 * Worktree contract — Zod schema for `.worktree-meta.json` plus the port-range
 * constants that bound the schema's `claimed_port` field.
 *
 * Single source of truth for the worktree metadata shape and instance port range.
 * Used by:
 * - cli/src/daemon/worktreeMeta.ts (writeWorktreeMeta, claimWorktreePort) — wraps
 *   this module and re-exports for backward-compatible relative-path callers
 * - cli/src/daemon/run.ts (post-createWorktree wiring)
 * - 6 bash scripts that read .worktree-meta.json or use the port range
 * - ~/.claude/hooks/issue-worker-detector.py (mutates issue_number, feature_branch)
 *
 * `claimed_port` is nullable to support:
 * - hapi-worktree.sh:cmd_stop clearing the port to null after stopping
 * - The two-phase write design (createWorktree writes everything except port;
 *   port-claim path patches it later)
 *
 * `last_port` is a durable, never-nulled worktree→port backlink (#2231): the port
 * this worktree last started on. Set on every real claim and preserved across TS
 * full rewrites by writeWorktreeMeta's read-before-write (#3209). It survives the
 * `claimed_port`-only null-out traps, so `release-worktree-port.sh` can still find
 * and reap a live-but-unclaimed instance. Placed before `claimed_port` so
 * `claimed_port` stays the LAST key (its truncation-loss analysis in
 * hapi-worktree.sh:266-270). Nullable+defaulted → backward-compatible add.
 *
 * `schema_version` exists for future migrations. Existing files without the field
 * parse via `.default(1)`. `.passthrough()` accepts forward-compatible additions.
 *
 * Bash scripts get equivalent constant values via `scripts/lib/worktree-constants.sh`,
 * regenerated by `scripts/generate-worktree-constants.ts` during build.
 *
 * Layout note: this file consolidates the schema and constants previously split
 * across `types/worktreeMeta.ts` and `constants/worktree.ts` (issue #1174 — flat
 * file convention matches the rest of `shared/src/`).
 */

export const WORKTREE_PORT_MIN = 3010 as const;
export const WORKTREE_PORT_MAX = 3019 as const;

export const WorktreeMetaSchema = z
  .object({
    schema_version: z.literal(1).default(1),
    created_at: z.string().min(1),
    source_branch: z.string().min(1),
    feature_branch: z.string().min(1),
    issue_number: z.number().int().nullable(),
    session_id: z.string().min(1),
    last_port: z.number().int().nullable().default(null),
    claimed_port: z.number().int().nullable(),
    /**
     * hapimatic-private#4481: present ONLY for a worktree opened on a branch
     * that already existed (absent = the session created the branch — the
     * pre-#4481 shape, kept byte-identical with the bash writer). Consumers:
     * `syncConfigFromMain` skips the `.claude/` re-sync for both values; the
     * cleanup paths never `git branch -D` an `existing-local` branch.
     */
    branch_origin: z.enum(["existing-local", "existing-remote"]).optional(),
  })
  .passthrough();

export type WorktreeMeta = z.infer<typeof WorktreeMetaSchema>;

export type ValidateResult =
  | { ok: true; meta: WorktreeMeta }
  | { ok: false; error: string };

/**
 * Validate an unknown input against the worktree-meta schema.
 *
 * Returns `{ok: true, meta}` on success or `{ok: false, error}` with the Zod
 * error message on failure. Never throws.
 */
export function validateWorktreeMeta(input: unknown): ValidateResult {
  const result = WorktreeMetaSchema.safeParse(input);
  if (result.success) return { ok: true, meta: result.data };
  return { ok: false, error: result.error.message };
}
