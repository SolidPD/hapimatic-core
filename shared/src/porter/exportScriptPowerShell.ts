    "    $script:OMISSIONS += ([ordered]@{ surface = $surface; reason = $reason })",
    "  }",
    "  # StrictMode-safe optional property read (a missing property would THROW).",
    "  function propOrNull($obj, $name) {",
    "    if ($null -eq $obj) { return $null }",
    "    $p = $obj.PSObject.Properties[$name]",
    "    if ($p) { return $p.Value } else { return $null }",
    "  }",
    "  # #4324: StrictMode-safe property NAMES. .Name over an empty Properties list",
    "  # throws, and an empty object is still truthy. Only an object has names: a",
    "  # JSON string would list Length, and on 5.1 a [] would list the array's members.",
    "  function propNames($obj) {",
    "    if ($null -eq $obj) { return @() }",
    "    if ($obj -isnot [System.Management.Automation.PSCustomObject]) { return @() }",
