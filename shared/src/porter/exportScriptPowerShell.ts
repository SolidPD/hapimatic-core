    "    # backslash is a name byte and is kept.",
    "    function stagedRel($full) {",
    "      $r = $full.Substring($STG_FULL.Length)",
    "      if ($ON_WINDOWS) { return ($r.TrimStart('\\', '/') -replace '\\\\', '/') }",
    "      return $r.TrimStart('/')",
    "    }",
    "    # True when $full, read by .NET, lies inside staging.",
    "    function inStaging($full) {",
    "      $cmp = if ($ON_WINDOWS) { [StringComparison]::OrdinalIgnoreCase } else { [StringComparison]::Ordinal }",
    "      return [IO.Path]::GetFullPath($full).StartsWith($STG_FULL + [IO.Path]::DirectorySeparatorChar, $cmp)",
    "    }",
    "    # Removes one staged file, folder or link (a FileSystemInfo). A link is",
    "    # removed as a link (a recursive Remove-Item can delete through one), and",
    "    # off Windows the removal is .NET's, whose recursive delete never follows",
    "    # a link either. A path outside staging stops the export.",
    "    function removeStaged($it) {",
    "      if (-not (inStaging $it.FullName)) { throw ('refusing to remove a path outside the staging folder: ' + $it.FullName) }",
    "      if ($it.Attributes -band [IO.FileAttributes]::ReparsePoint) {",
    "        if ($it -is [IO.DirectoryInfo]) { [IO.Directory]::Delete($it.FullName, $false) } else { [IO.File]::Delete($it.FullName) }",
    "      } elseif ($ON_WINDOWS) {",
    "        Remove-Item -LiteralPath $it.FullName -Recurse -Force",
    "      } elseif ($it -is [IO.DirectoryInfo]) {",
    "        # A name under it that .NET cannot read (see unreadableName), or a",
    "        # folder without write permission, makes the recursive delete fail:",
    "        # stop with a message that names both causes.",
    "        try { $it.Delete($true) } catch { throw ('porter: PowerShell could not remove the staged ' + (stagedRel $it.FullName) + ' (' + $_.Exception.Message + '). A name under it may not be valid UTF-8, or a folder may lack write permission. Its staging copy stays in ' + $STG_FULL + '; delete that folder (make it writable first, for example with chmod -R u+w).') }",
    "      } else {",
    "        $it.Delete()",
    "      }",
    "    }",
    "    # Stops the export on a staged name PowerShell cannot read off Windows: its",
    "    # bytes are not valid UTF-8, so .NET decodes it with a replacement",
    "    # character (U+FFFD). The path it builds then names nothing (its attributes",
    "    # read as -1), or names a sibling that really holds U+FFFD, so the same",
    "    # name appears twice in one listing. It could be neither checked nor",
    "    # removed, and tar would still pack it. The staging copy cannot be removed",
    "    # either, so the message says where it is. A name that really holds U+FFFD",
    "    # is read as it is and exports.",
    "    function unreadableName($it) {",
    "      throw ('porter: PowerShell cannot read a staged name: ' + (stagedRel $it.FullName) + ' (its bytes are not valid UTF-8, so .NET reads it as another name or as none). Rename it in your configuration: if a sibling there reads the same, rename the one that is not valid UTF-8. Its staging copy stays in ' + $STG_FULL + '; delete that folder (make it writable first, for example with chmod -R u+w).')",
    "    }",
    "    # The entries of a staged folder (a DirectoryInfo): off Windows by .NET,",
    "    # never by a cmdlet given the folder's path as a string.",
    "    function stagedChildren($dir) {",
    "      if ($ON_WINDOWS) { return @(Get-ChildItem -LiteralPath $dir.FullName -Force) }",
    "      $kids = @($dir.EnumerateFileSystemInfos())",
    "      $seen = New-Object 'System.Collections.Generic.HashSet[string]' ([StringComparer]::Ordinal)",
    "      foreach ($k in $kids) { if (([int]$k.Attributes -eq -1) -or -not $seen.Add($k.Name)) { unreadableName $k } }",
    "      return $kids",
    "    }",
    "    # The staged file, folder or link at $rel ('/'-separated, or the",
    "    # platform's separator on Windows), or $null. Off Windows it is read by",
    "    # .NET, so a backslash in a name stays in that name.",
    "    function stagedItem($rel) {",
    "      if ($ON_WINDOWS) { return (Get-Item -LiteralPath (Join-Path $STAGING $rel) -Force -ErrorAction SilentlyContinue) }",
    "      $p = $STG_FULL",
    "      foreach ($part in $rel.Split([char[]]@('/'), [StringSplitOptions]::RemoveEmptyEntries)) { $p = [IO.Path]::Combine($p, $part) }",
    "      if (-not (inStaging $p)) { return $null }",
    "      $a = (New-Object IO.FileInfo $p).Attributes",
    "      if ([int]$a -eq -1) { return $null }",
    "      if (($a -band [IO.FileAttributes]::Directory) -eq [IO.FileAttributes]::Directory) { return (New-Object IO.DirectoryInfo $p) }",
    "      return (New-Object IO.FileInfo $p)",
    "    }",
    "",
    "    # ---- materialize reparse points (the import refuses link members) ----",
    "    # Replace every staged symlink/junction with its target's content (the",
    "    # target is resolved at the SOURCE location, the only place a relative",
    "    # link resolves). A directory target is tree-copied through the link with",
    "    # the same junk exclusions; a file target is copied from the physical path",
    "    # the check read (refused as unchecked when that path is not a file); an",
    "    # unresolvable target is dropped and recorded as an omission with the bash",
