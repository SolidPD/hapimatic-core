/**
 * #3448 (Sub C): render a NON-Claude-Code source's candidate MCP config paths
 * (from the shared {@link SOURCE_CONFIG_PATHS} table) as PowerShell path
 * EXPRESSIONS (each yields a full path or `$null`). `home` → `$HOME_DIR`
 * (USERPROFILE-or-HOME, defined in preflight); `appdata` → `$env:APPDATA` guarded
 * to `$null` when empty (Linux-pwsh has no APPDATA); `xdg-config` →
 * `$env:XDG_CONFIG_HOME` else `$HOME_DIR/.config`. Probed by existence in order.
 */
function powershellSourcePathExprs(
  id: Exclude<PorterSourceId, "claude-code" | "codex">
): string[] {
  return SOURCE_CONFIG_PATHS[id].map(p => {
    const seg = psq(p.segments);
    if (p.base === "home") return `(Join-Path $HOME_DIR ${seg})`;
    if (p.base === "appdata") {
      return `$(if ($env:APPDATA) { Join-Path $env:APPDATA ${seg} } else { $null })`;
    }
    return `(Join-Path $(if ($env:XDG_CONFIG_HOME) { $env:XDG_CONFIG_HOME } else { Join-Path $HOME_DIR '.config' }) ${seg})`;
  });
}

/** A PowerShell array literal `@('a', 'b', …)` from string elements. */
function psArray(items: readonly string[]): string {
  return `@(${items.map(psq).join(", ")})`;
}

