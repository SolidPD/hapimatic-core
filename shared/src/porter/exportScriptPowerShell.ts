    // uses os.homedir() = USERPROFILE on Windows); else $HOME\.claude (Linux-pwsh).
    "  if ($env:CLAUDE_CONFIG_DIR) {",
    "    $CONFIG_ROOT = $env:CLAUDE_CONFIG_DIR",
    "  } elseif ($env:USERPROFILE) {",
    "    $CONFIG_ROOT = Join-Path $env:USERPROFILE '.claude'",
    "  } else {",
    "    $CONFIG_ROOT = Join-Path $HOME '.claude'",
    "  }",
    "  # ---- P7a guard (K12/D8(a)) - WARN-ONLY (mirror the bash quirk) ----",
    "  $HOME_CLAUDE = if ($env:USERPROFILE) { Join-Path $env:USERPROFILE '.claude' } else { Join-Path $HOME '.claude' }",
    "  if ($env:CLAUDE_CONFIG_DIR -and ($env:CLAUDE_CONFIG_DIR -ne $HOME_CLAUDE)) {",
    "    [Console]::Error.WriteLine('warning: CLAUDE_CONFIG_DIR is set to ' + $env:CLAUDE_CONFIG_DIR + ' (not ' + $HOME_CLAUDE + ')')",
    "    [Console]::Error.WriteLine('         this looks like a Hapimatic session terminal - run the command in a')",
    "    [Console]::Error.WriteLine('         regular terminal if you meant your personal config.')",
    "  }",
    // HOST_CONFIG = the home .claude.json, IGNORING CLAUDE_CONFIG_DIR (the bash
    // `HOST_CONFIG="$HOME/.claude.json"` quirk); USERPROFILE-first so it finds the
    // file where Claude Code's os.homedir() wrote it on Windows.
    "  if ($env:USERPROFILE) {",
    "    $HOST_CONFIG = Join-Path $env:USERPROFILE '.claude.json'",
    "  } else {",
    "    $HOST_CONFIG = Join-Path $HOME '.claude.json'",
    "  }",
    "  # ---- Preflight relax (#3448 Sub C, 1B#34) - $CONFIG_ROOT feeds only the",
    "  # claude-code source; Cursor / Claude Desktop live elsewhere. Record its",
    "  # presence and continue; the 'no source found' error moves to Step 5.",
    "  $CLAUDE_CODE_FOUND = (Test-Path -LiteralPath $CONFIG_ROOT -PathType Container)",
    "  $HOME_DIR = if ($env:USERPROFILE) { $env:USERPROFILE } else { $HOME }",
    "",
    "  # Staging holds the archive tree; WORK holds scratch kept OUT of the tar.",
    "  $STAGING = Join-Path ([IO.Path]::GetTempPath()) ([IO.Path]::GetRandomFileName())",
    "  $WORK = Join-Path ([IO.Path]::GetTempPath()) ([IO.Path]::GetRandomFileName())",
