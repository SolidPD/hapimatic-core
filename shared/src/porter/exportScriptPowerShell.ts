    // the CI equivalence leg).
    "  if ($env:SystemRoot) {",
    "    $TAR = Join-Path $env:SystemRoot 'System32\\tar.exe'",
    "    if (-not (Test-Path -LiteralPath $TAR -PathType Leaf)) {",
    "      throw 'tar.exe not found - Windows 10 1803+ required'",
