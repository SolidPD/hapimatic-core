/**
 * Configuration Porter — Windows-native PowerShell export twin (epic #3445
 * Sub B, issue #3447).
 *
 * {@link buildExportScriptPowerShell} is the PORT of {@link buildExportScript}:
 * a self-contained PowerShell script the user runs DIRECTLY on their SOURCE
 * machine (no Claude/LLM step, no WSL) that packages `%USERPROFILE%\.claude`
 * (or `$CLAUDE_CONFIG_DIR`) into a definitions-only `.tar.gz` — a MANIFEST-
 * EQUIVALENT archive to the bash emitter's, provable member-for-member and
 * (after key-sort/normalise) manifest-for-manifest by the cross-emitter
 * equivalence harness (`server/src/porter/exportEquivalence.test.ts`, K13/D7).
 *
 * 🔴 SECRETS-FREE BY DESIGN (R2), identical to the bash twin: the script
 * collects only config DEFINITIONS, never a secret VALUE. MCP env/header/url/
 * args secret SLOTS are DECLARED by name (so the destination re-auths) but their
 * values are never read; `settings.env` VALUES are omitted entirely. The archive
 * self-marks definitions-only via {@link DEFINITIONS_ONLY_SECRETS_OMISSION}.
 *
 * PLACEMENT / PURITY — like `buildExportScript`, a PURE function in `shared/`
 * (no `node:*` imports, no I/O): it produces POWERSHELL TEXT. The `manifest.test.ts`
 * R7 guard fails the build if a non-test module here imports `node:`.
 *
 * DRIFT PREVENTION — every dimension name, exclusion pattern, settings key, and
 * secret/marketplace regex is IMPORTED from {@link exportShared} (the K7 hoist),
 * `manifest.ts`, `version.ts` and `exportNaming.ts`, never restated — so the bash
 * and PowerShell emitters cannot disagree on what a definitions-only archive is.
 *
 * 5.1 + 7 COMPAT (R2). The script runs under BOTH Windows PowerShell 5.1 (the
 * `irm | iex` default) and PowerShell 7, so it avoids every 6.1+/7-only feature:
 * no `??`/`?.`/ternary, no `-Form`, no `-SkipCertificateCheck`, no native pipes
 * (5.1 and pwsh < 7.4 re-encode native-to-native pipes — 1B#19), no `exit` (`iex`
 * runs in the caller's scope, so `exit` would end the console — the whole body is
 * a `& { }` scope block that `throw`s instead — 1B#18), BOM-free `manifest.json`
 * (5.1's `-Encoding UTF8` writes a BOM — 1B#16), `System32\tar.exe` resolved
 * explicitly (1B#20), one `HttpClient` upload path (1B#26).
 */
