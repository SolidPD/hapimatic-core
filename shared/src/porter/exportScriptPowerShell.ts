    "  [Console]::Error.WriteLine('')",
    "  [Console]::Error.WriteLine('== Hapimatic Configuration Porter - secrets-free, symlink-safe export ==')",
    "  [Console]::Error.WriteLine('Collecting your Claude Code configuration. Depending on its size this')",
    "  [Console]::Error.WriteLine('can take a few minutes; each step reports below as it starts.')",
