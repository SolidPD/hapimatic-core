/**
 * Configuration Porter — the PowerShell lines of the Codex source (issue
 * #5169), the twin of `codexSourceShell.ts` and a sibling of
 * `exportScriptPowerShell.ts` so that file grows only by its call sites. The
 * dialect-neutral rules live in `codexSource.ts`; `exportEquivalence.test.ts`
 * pins the two dialects.
 *
 * The TOML reader below is the bash twin's jq program written out in
 * PowerShell, transition for transition: the same token regex, the same
 * modes, the same refusals. Every comparison of TOML text is case-sensitive
 * (`-ceq`, `-ccontains`, ordinal dictionaries), as TOML is.
 *
 * The lines run inside the PowerShell exporter's main block and rely on its
 * helpers and state: `recordOmission`, `pruneCredentialNames`, `physicalPath`
 * (with `$script:ppCred`), `hasCredentialPart`, `linkRootRefusal`,
 * `pathExists`, `copyTreeExcluding`, `stagedChildren`, `stagedRel`,
 * `removeStaged`, `extractMcp`, `$STAGING`, `$STG_FULL`, `$HOME_DIR`,
 * `$DIM_JSON` and `$DIMENSION_FIELD`.
 *
 * NODE-FREE: string builders only. Windows PowerShell 5.1 syntax only (no
 * ternary, no `??`, no `::new` on a type 5.1 lacks).
 */
