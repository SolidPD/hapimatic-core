/** A PowerShell array literal of strings. */
function psArr(items: readonly string[]): string {
  return `@(${items.map(psq).join(", ")})`;
}

/**
 * Preflight (after `$HOME_DIR`): where Codex's home is, and whether it exists.
 * An empty `CODEX_HOME` is unset (PowerShell reads an empty variable as false).
 */
export function codexDiscoveryPowerShellLines(): string[] {
  return [
    "  # #5169: Codex's home ($env:CODEX_HOME, else ~/.codex; an empty value is unset).",
    "  $CODEX_ROOT = if ($env:CODEX_HOME) { $env:CODEX_HOME } else { Join-Path $HOME_DIR '.codex' }",
    "  if (-not [IO.Path]::IsPathRooted($CODEX_ROOT)) { $CODEX_ROOT = Join-Path (Get-Location).ProviderPath $CODEX_ROOT }",
    "  $CODEX_FOUND = (Test-Path -LiteralPath $CODEX_ROOT -PathType Container)",
    "  $CODEX_READ = $false",
    "  $CODEX_PHYS = $null",
  ];
}

/**
 * The reader's functions: `cxReadToml $path` returns `$null` (the file cannot
 * be read) or `@{ root; unsupported; dropped }`, where `root` is an object
 * shaped like a `~/.claude.json` root (`mcpServers`), so it goes straight to
 * `extractMcp`, with every env and header value `''`.
 */
export function codexReaderPowerShellLines(): string[] {
  const ord = "[StringComparer]::Ordinal";
  const list = "(New-Object 'System.Collections.Generic.List[string]')";
  return [
    "    # ---- #5169: the Codex config.toml subset reader (the bash twin's jq, line for line) ----",
    `    $cxTokRe = [regex]::new(${psq(CODEX_TOML_TOKEN_PATTERN)})`,
    `    $cxBasicRe = [regex]::new(${psq(CODEX_TOML_BASIC_BODY_PATTERN)})`,
    `    $cxLitRe = [regex]::new(${psq(CODEX_TOML_LITERAL_BODY_PATTERN)})`,
    `    $cxBareRe = [regex]::new(${psq(CODEX_TOML_BARE_KEY_PATTERN)})`,
    `    $cxMaps = ${psArr(CODEX_MCP_MAP_FIELDS)}`,
    `    $cxStrF = ${psArr(CODEX_MCP_STRING_FIELDS)}`,
    "    function cxKind($t) {",
    '      if (($t -ceq "`n") -or ($t -ceq "`r`n")) { return \'NL\' }',
    "      $c = $t.Substring(0, 1)",
    "      if (($c -ceq ' ') -or ($c -ceq \"`t\")) { return 'WS' }",
    "      if ($c -ceq '#') { return 'COM' }",
    "      if ($t.StartsWith('\"\"\"', [StringComparison]::Ordinal)) { return 'MLB' }",
    "      if ($t.StartsWith(\"'''\", [StringComparison]::Ordinal)) { return 'MLL' }",
    "      if (($c -ceq '\"') -and ($t.Length -ge 2)) { return 'BS' }",
    "      if (($c -ceq \"'\") -and ($t.Length -ge 2)) { return 'LS' }",
    "      if (($t.Length -eq 1) -and ('[]{}=,.'.Contains($t))) { return 'P' }",
    "      if ($t -cmatch '^[A-Za-z0-9_+:-]+$') { return 'BARE' }",
    "      return 'ERR'",
    "    }",
    "    function cxBdec($t) {",
    "      $in = $t.Substring(1, $t.Length - 2)",
    "      if (-not $cxBasicRe.IsMatch($in)) { return $null }",
    "      return [regex]::Replace($in, '\\\\(?:u([0-9A-Fa-f]{4})|(.))', [System.Text.RegularExpressions.MatchEvaluator]{",
    "        param($mm)",
    "        if ($mm.Groups[1].Success) { return [string][char][Convert]::ToInt32($mm.Groups[1].Value, 16) }",
    "        $e = $mm.Groups[2].Value",
    "        if ($e -ceq 'b') { return [string][char]8 }",
    "        if ($e -ceq 't') { return [string][char]9 }",
    "        if ($e -ceq 'n') { return [string][char]10 }",
    "        if ($e -ceq 'f') { return [string][char]12 }",
    "        if ($e -ceq 'r') { return [string][char]13 }",
    "        return $e",
    "      })",
    "    }",
    "    function cxLdec($t) {",
    "      $in = $t.Substring(1, $t.Length - 2)",
    "      if ($cxLitRe.IsMatch($in)) { return $in }",
    "      return $null",
    "    }",
    "    function cxSdec($o) {",
    "      if ($o[1] -ceq 'BS') { return (cxBdec $o[0]) }",
    "      if ($o[1] -ceq 'LS') { return (cxLdec $o[0]) }",
    "      return $null",
    "    }",
    "    function cxKdec($o) {",
    "      if ($o[1] -ceq 'BARE') { if ($cxBareRe.IsMatch($o[0])) { return $o[0] } else { return $null } }",
    "      return (cxSdec $o)",
    "    }",
    "    function cxIsStr($o) { return (($o[1] -ceq 'BS') -or ($o[1] -ceq 'LS')) }",
    "    function cxSk($a) { return ([string[]]$a -join [string][char]0) }",
    "    function cxUnsup($st, $s) { $st.U.Add([string]$s) }",
    "    function cxMark($st, $a) { $st.seen[(cxSk $a)] = $true }",
    "    function cxSeen($st, $a) { return $st.seen.ContainsKey((cxSk $a)) }",
    "    function cxEnsure($st, $s) {",
    "      if (-not $st.S.ContainsKey($s)) {",
    `        $st.S[$s] = @{ cmd = $null; url = $null; args = $null; en = $null; bearer = $false; has = ${list}; drop = ${list}; keys = @{ env = ${list}; http_headers = ${list}; env_http_headers = ${list} } }`,
    "      }",
    "    }",
    "    function cxSkipTok($st, $o) {",
    "      $t = $o[0]",
    "      if ($o[1] -ceq 'P' -and (($t -ceq '[') -or ($t -ceq '{'))) { $st.d = $st.d + 1 }",
    "      elseif ($o[1] -ceq 'P' -and (($t -ceq ']') -or ($t -ceq '}'))) { $st.d = $st.d - 1; if ($st.d -lt 0) { $st.bad = $true } }",
    "      elseif (($o[1] -ceq 'NL') -and ($st.d -eq 0)) { $st.m = 'S' }",
    "    }",
    "    function cxToSkip($st, $o) { $st.m = 'SKIP'; cxSkipTok $st $o }",
    "    function cxFail($st, $o) { cxUnsup $st $st.ts; cxToSkip $st $o }",
    "    function cxKeyFail($st, $o) { if (($st.tk -ceq 'srv') -or ($st.tk -ceq 'map')) { cxFail $st $o } else { $st.bad = $true } }",
    "    function cxKeyPart($st, $o) { $p = cxKdec $o; if ($null -ne $p) { $st.kp.Add($p); $st.m = 'KD' } else { cxKeyFail $st $o } }",
    "    function cxHKeyPart($st, $o) { $p = cxKdec $o; if ($null -ne $p) { $st.hp.Add($p); $st.m = 'HD' } else { $st.bad = $true } }",
    "    function cxFinishHeader($st) {",
    "      $p = $st.hp; $n = $p.Count",
    "      if ($p[0] -cne 'mcp_servers') { $st.tk = 'other'; return }",
    "      if ($st.ha) { if ($n -eq 1) { $st.bad = $true } else { cxUnsup $st $p[1]; $st.tk = 'ign' }; return }",
    "      if ($n -eq 1) { $st.tk = 'mcproot'; return }",
    "      $s = $p[1]; cxEnsure $st $s; $st.ts = $s",
    "      if ($n -eq 2) {",
    "        if (cxSeen $st @('h', $s)) { cxUnsup $st $s }",
    "        cxMark $st @('h', $s); $st.tk = 'srv'; return",
    "      }",
    "      $f = $p[2]",
    "      if ($cxMaps -ccontains $f) {",
    "        if ($n -ge 4) { cxUnsup $st $s; $st.tk = 'ign'; return }",
    "        if ((cxSeen $st @('t', $s, $f)) -or (cxSeen $st @('a', $s, $f)) -or (cxSeen $st @('d', $s, $f))) { cxUnsup $st $s }",
    "        cxMark $st @('t', $s, $f); $st.S[$s].has.Add($f); $st.tk = 'map'; $st.tf = $f; return",
    "      }",
    "      $st.S[$s].drop.Add($f); $st.tk = 'ign'",
    "    }",
    "    function cxBeginValue($st) {",
    "      $k = $st.kp; $n = $k.Count; $p0 = $k[0]",
    "      if ($st.tk -ceq 'root') {",
    "        if ($p0 -ceq 'mcp_servers') { if ($n -eq 1) { $st.bad = $true; return } else { cxUnsup $st $k[1] } }",
    "        $st.m = 'SKIP'; $st.d = 0; return",
    "      }",
    "      if ($st.tk -ceq 'mcproot') { cxUnsup $st $p0; $st.m = 'SKIP'; $st.d = 0; return }",
    "      $s = $st.ts",
    "      if ($st.tk -ceq 'srv') {",
    "        if (($n -eq 1) -and ($cxStrF -ccontains $p0)) {",
    "          if (cxSeen $st @('k', $s, $p0)) { cxUnsup $st $s }",
    "          cxMark $st @('k', $s, $p0); $st.vc = 'str'; $st.tf = $p0; $st.m = 'V'; return",
    "        }",
    "        if (($n -eq 1) -and (($p0 -ceq 'args') -or ($p0 -ceq 'enabled'))) {",
    "          if (cxSeen $st @('k', $s, $p0)) { cxUnsup $st $s }",
    "          cxMark $st @('k', $s, $p0)",
    "          if ($p0 -ceq 'args') { $st.vc = 'arr' } else { $st.vc = 'bool' }",
    "          $st.m = 'V'; return",
    "        }",
    "        if (($n -eq 1) -and ($cxMaps -ccontains $p0)) {",
    "          if ((cxSeen $st @('t', $s, $p0)) -or (cxSeen $st @('d', $s, $p0)) -or (cxSeen $st @('a', $s, $p0))) { cxUnsup $st $s }",
    "          cxMark $st @('a', $s, $p0); $st.vc = 'itab'; $st.tf = $p0; $st.m = 'V'; return",
    "        }",
    "        if (($n -eq 2) -and ($cxMaps -ccontains $p0)) {",
    "          if ((cxSeen $st @('t', $s, $p0)) -or (cxSeen $st @('a', $s, $p0)) -or (cxSeen $st @('k', $s, $p0, $k[1]))) { cxUnsup $st $s }",
    "          cxMark $st @('d', $s, $p0); cxMark $st @('k', $s, $p0, $k[1])",
    "          $st.vc = 'mstr'; $st.tf = $p0; $st.tk2 = $k[1]; $st.m = 'V'; return",
    "        }",
    "        if ($cxMaps -ccontains $p0) { cxUnsup $st $s; $st.m = 'SKIP'; $st.d = 0; return }",
    "        $st.S[$s].drop.Add($p0); $st.m = 'SKIP'; $st.d = 0; return",
    "      }",
    "      if ($st.tk -ceq 'map') {",
    "        $f = $st.tf",
    "        if ($n -eq 1) {",
    "          if (cxSeen $st @('k', $s, $f, $p0)) { cxUnsup $st $s }",
    "          cxMark $st @('k', $s, $f, $p0); $st.vc = 'mstr'; $st.tk2 = $p0; $st.m = 'V'; return",
    "        }",
    "        cxUnsup $st $s; $st.m = 'SKIP'; $st.d = 0; return",
    "      }",
    "      $st.m = 'SKIP'; $st.d = 0",
    "    }",
    "    function cxAssignStr($st, $v) {",
    "      $s = $st.ts; $f = $st.tf",
    "      if (($v -ceq '') -and (($f -ceq 'command') -or ($f -ceq 'url'))) { cxUnsup $st $s }",
    "      elseif ($f -ceq 'command') { $st.S[$s].cmd = $v }",
    "      elseif ($f -ceq 'url') { $st.S[$s].url = $v }",
    "      else { $st.S[$s].bearer = $true }",
    "      $st.S[$s].has.Add($f)",
    "    }",
    "    function cxAddKey($st, $key) {",
    "      $s = $st.ts; $f = $st.tf",
    "      if ($key -ceq '') { cxUnsup $st $s } else { $st.S[$s].keys[$f].Add($key); $st.S[$s].has.Add($f) }",
    "    }",
    "    function cxAssignItab($st) {",
    "      $s = $st.ts; $f = $st.tf",
    "      $st.S[$s].has.Add($f)",
    `      $u = New-Object 'System.Collections.Generic.HashSet[string]' (${ord})`,
    "      $dup = $false",
    "      foreach ($x in $st.itk) { if (($x -ceq '') -or -not $u.Add($x)) { $dup = $true } }",
    "      if ($dup) { cxUnsup $st $s } else { $st.S[$s].keys[$f].AddRange($st.itk) }",
    "    }",
    "    function cxValue1($st, $o) {",
    "      if ($st.vc -ceq 'str') { $v = cxSdec $o; if ($null -eq $v) { cxFail $st $o } else { cxAssignStr $st $v; $st.m = 'VE' }; return }",
    "      if ($st.vc -ceq 'mstr') { if (cxIsStr $o) { cxAddKey $st $st.tk2; $st.m = 'VE' } else { cxFail $st $o }; return }",
    "      if ($st.vc -ceq 'bool') {",
    "        if (($o[1] -ceq 'BARE') -and (($o[0] -ceq 'true') -or ($o[0] -ceq 'false'))) {",
    "          $st.S[$st.ts].en = ($o[0] -ceq 'true'); $st.S[$st.ts].has.Add('enabled'); $st.m = 'VE'",
    "        } else { cxFail $st $o }",
    "        return",
    "      }",
    "      if ($st.vc -ceq 'arr') { if (($o[1] -ceq 'P') -and ($o[0] -ceq '[')) { $st.d = 1; $st.arr.Clear(); $st.ast = 'e'; $st.m = 'VA' } else { cxFail $st $o }; return }",
    "      if (($o[1] -ceq 'P') -and ($o[0] -ceq '{')) { $st.d = 1; $st.itk.Clear(); $st.ist = 'k0'; $st.m = 'VI' } else { cxFail $st $o }",
    "    }",
    "    function cxVArr($st, $o) {",
    "      if ($o[1] -ceq 'NL') { return }",
    "      if (($o[1] -ceq 'P') -and ($o[0] -ceq ']')) { $st.d = 0; $st.S[$st.ts].args = [string[]]$st.arr.ToArray(); $st.S[$st.ts].has.Add('args'); $st.m = 'VE'; return }",
    "      if ($st.ast -ceq 'e') {",
    "        if (cxIsStr $o) { $v = cxSdec $o; if ($null -eq $v) { cxFail $st $o } else { $st.arr.Add($v); $st.ast = 'c' } } else { cxFail $st $o }",
    "        return",
    "      }",
    "      if (($o[1] -ceq 'P') -and ($o[0] -ceq ',')) { $st.ast = 'e' } else { cxFail $st $o }",
    "    }",
    "    function cxVItab($st, $o) {",
    "      $pt = ($o[1] -ceq 'P')",
    "      if (($st.ist -ceq 'k0') -and $pt -and ($o[0] -ceq '}')) { $st.d = 0; cxAssignItab $st; $st.m = 'VE'; return }",
    "      if (($st.ist -ceq 'k0') -or ($st.ist -ceq 'k')) { $p = cxKdec $o; if ($null -ne $p) { $st.ikey = $p; $st.ist = 'e' } else { cxFail $st $o }; return }",
    "      if ($st.ist -ceq 'e') { if ($pt -and ($o[0] -ceq '=')) { $st.ist = 'v' } else { cxFail $st $o }; return }",
    "      if ($st.ist -ceq 'v') { if (cxIsStr $o) { $st.itk.Add($st.ikey); $st.ist = 'c' } else { cxFail $st $o }; return }",
    "      if ($pt -and ($o[0] -ceq ',')) { $st.ist = 'k'; return }",
    "      if ($pt -and ($o[0] -ceq '}')) { $st.d = 0; cxAssignItab $st; $st.m = 'VE'; return }",
    "      cxFail $st $o",
    "    }",
    "    function cxStep($st, $o) {",
    "      if ($st.bad) { return }",
    "      if ($o[1] -ceq 'ERR') { $st.bad = $true; return }",
    "      $pt = ($o[1] -ceq 'P'); $t = $o[0]; $m = $st.m",
    "      if ($m -ceq 'S') {",
    "        if ($o[1] -ceq 'NL') { return }",
    "        if ($pt -and ($t -ceq '[')) { $st.m = 'H0'; $st.hp.Clear(); $st.ha = $false; return }",
    "        if (($st.tk -ceq 'other') -or ($st.tk -ceq 'ign')) { cxToSkip $st $o; return }",
    "        $st.kp.Clear(); cxKeyPart $st $o; return",
    "      }",
    "      if ($m -ceq 'H0') { if ($pt -and ($t -ceq '[')) { $st.ha = $true; $st.m = 'HK' } else { cxHKeyPart $st $o }; return }",
    "      if ($m -ceq 'HK') { cxHKeyPart $st $o; return }",
    "      if ($m -ceq 'HD') {",
    "        if ($pt -and ($t -ceq '.')) { $st.m = 'HK' }",
    "        elseif ($pt -and ($t -ceq ']')) { if ($st.ha) { $st.m = 'HC' } else { cxFinishHeader $st; $st.m = 'HE' } }",
    "        else { $st.bad = $true }",
    "        return",
    "      }",
    "      if ($m -ceq 'HC') { if ($pt -and ($t -ceq ']')) { cxFinishHeader $st; $st.m = 'HE' } else { $st.bad = $true }; return }",
    "      if ($m -ceq 'HE') { if ($o[1] -ceq 'NL') { $st.m = 'S' } else { $st.bad = $true }; return }",
    "      if ($m -ceq 'K') { cxKeyPart $st $o; return }",
    "      if ($m -ceq 'KD') {",
    "        if ($pt -and ($t -ceq '.')) { $st.m = 'K' }",
    "        elseif ($pt -and ($t -ceq '=')) { cxBeginValue $st }",
    "        else { cxKeyFail $st $o }",
    "        return",
    "      }",
    "      if ($m -ceq 'V') { cxValue1 $st $o; return }",
    "      if ($m -ceq 'VA') { cxVArr $st $o; return }",
    "      if ($m -ceq 'VI') { cxVItab $st $o; return }",
    "      if ($m -ceq 'VE') { if ($o[1] -ceq 'NL') { $st.m = 'S' } else { cxFail $st $o }; return }",
    "      cxSkipTok $st $o",
    "    }",
    "    # A name list with no two names equal when ASCII case is ignored (the jq",
    "    # twin's ascii_downcase test). A PowerShell object cannot hold two such",
    "    # property names, so the reader refuses them rather than throw.",
    "    function cxAsciiLower($x) { return [regex]::Replace([string]$x, '[A-Z]', { param($mm) $mm.Value.ToLowerInvariant() }) }",
    "    function cxCaseClash($names) {",
    `      $u = New-Object 'System.Collections.Generic.HashSet[string]' (${ord})`,
    "      foreach ($x in $names) {",
    "        if (-not $u.Add((cxAsciiLower $x))) { return $true }",
    "      }",
    "      return $false",
    "    }",
    "    function cxSorted($items) {",
    `      $h = New-Object 'System.Collections.Generic.HashSet[string]' (${ord})`,
    "      foreach ($x in $items) { $null = $h.Add([string]$x) }",
    "      $a = [string[]]@($h)",
    `      [Array]::Sort($a, ${ord})`,
    "      return ,$a",
    "    }",
    "    function cxNamesObject($names) {",
    "      $o = [PSCustomObject]@{}",
    "      foreach ($x in $names) { Add-Member -InputObject $o -NotePropertyName $x -NotePropertyValue '' }",
    "      return $o",
    "    }",
    "    function cxReadToml($path) {",
    "      $text = [Text.UTF8Encoding]::new($false).GetString([IO.File]::ReadAllBytes($path))",
    "      if (($text.Length -gt 0) -and ($text[0] -eq [char]0xFEFF)) { $text = $text.Substring(1) }",
    "      $toks = New-Object 'System.Collections.Generic.List[object]'",
    "      foreach ($mt in $cxTokRe.Matches($text)) {",
    "        $k = cxKind $mt.Value",
    "        if (($k -cne 'WS') -and ($k -cne 'COM')) { $toks.Add(@($mt.Value, $k)) }",
    "      }",
    "      $toks.Add(@(\"`n\", 'NL'))",
    `      $st = @{ m = 'S'; d = 0; tk = 'root'; ts = $null; tf = $null; tk2 = $null; ha = $false; vc = $null; ast = $null; ist = $null; ikey = $null; bad = $false; hp = ${list}; kp = ${list}; arr = ${list}; itk = ${list}; U = ${list} }`,
    `      $st.S = New-Object 'System.Collections.Generic.Dictionary[string,object]' (${ord})`,
    `      $st.seen = New-Object 'System.Collections.Generic.Dictionary[string,bool]' (${ord})`,
    "      foreach ($o in $toks) { $null = cxStep $st $o }",
    "      if ($st.bad -or ($st.m -cne 'S')) { return $null }",
    "      $unsup = New-Object 'System.Collections.Generic.List[string]'",
    "      $unsup.AddRange($st.U)",
    "      $names = cxSorted @($st.S.get_Keys())",
    "      $kept = New-Object 'System.Collections.Generic.List[object]'",
    "      foreach ($n in $names) {",
    "        $c = $st.S[$n]",
    "        $hasCmd = ($null -ne $c.cmd); $hasUrl = ($null -ne $c.url)",
    "        if (($st.U -ccontains $n) -or ($n -ceq '') -or ($hasCmd -eq $hasUrl)) { $unsup.Add($n); continue }",
    "        $e = [PSCustomObject]@{}",
    "        $f = New-Object 'System.Collections.Generic.List[string]'",
    "        $f.AddRange($c.drop)",
    "        if ($hasCmd) {",
    "          if (cxCaseClash $c.keys.env) { $unsup.Add($n); continue }",
    "          Add-Member -InputObject $e -NotePropertyName 'command' -NotePropertyValue $c.cmd",
    "          if ($null -ne $c.args) { Add-Member -InputObject $e -NotePropertyName 'args' -NotePropertyValue $c.args }",
    "          if ($c.keys.env.Count -gt 0) { Add-Member -InputObject $e -NotePropertyName 'env' -NotePropertyValue (cxNamesObject (cxSorted $c.keys.env)) }",
    `          foreach ($x in $c.has) { if (${psArr(CODEX_STDIO_UNUSED_FIELDS)} -ccontains $x) { $f.Add($x) } }`,
    "        } else {",
    "          $hl = New-Object 'System.Collections.Generic.List[string]'",
    "          $hl.AddRange($c.keys.http_headers); $hl.AddRange($c.keys.env_http_headers)",
    `          if ($c.bearer) { $hl.Add(${psq(CODEX_BEARER_HEADER)}) }`,
    "          $hs = cxSorted $hl",
    "          if (cxCaseClash $hs) { $unsup.Add($n); continue }",
    "          Add-Member -InputObject $e -NotePropertyName 'type' -NotePropertyValue 'http'",
    "          Add-Member -InputObject $e -NotePropertyName 'url' -NotePropertyValue $c.url",
    "          if ($hs.Count -gt 0) { Add-Member -InputObject $e -NotePropertyName 'headers' -NotePropertyValue (cxNamesObject $hs) }",
    `          foreach ($x in $c.has) { if (${psArr(CODEX_HTTP_UNUSED_FIELDS)} -ccontains $x) { $f.Add($x) } }`,
    "        }",
    "        if ($c.en -eq $false) { Add-Member -InputObject $e -NotePropertyName 'disabled' -NotePropertyValue $true }",
    "        $kept.Add(@($n, $e, (cxSorted $f)))",
    "      }",
    "      # Two kept names equal when ASCII case is ignored are both refused (the",
    "      # jq twin's rule; a PowerShell object cannot hold them as two properties).",
    `      $low = New-Object 'System.Collections.Generic.Dictionary[string,int]' (${ord})`,
    "      foreach ($k in $kept) { $lo = cxAsciiLower $k[0]; if ($low.ContainsKey($lo)) { $low[$lo] = $low[$lo] + 1 } else { $low[$lo] = 1 } }",
    "      $root = [PSCustomObject]@{}",
    "      $servers = [PSCustomObject]@{}",
    "      $dropped = @()",
    "      foreach ($k in $kept) {",
    "        if ($low[(cxAsciiLower $k[0])] -gt 1) { $unsup.Add($k[0]); continue }",
    "        Add-Member -InputObject $servers -NotePropertyName $k[0] -NotePropertyValue $k[1]",
    "        if ($k[2].Count -gt 0) { $dropped += ,@($k[0], $k[2]) }",
    "      }",
    "      Add-Member -InputObject $root -NotePropertyName 'mcpServers' -NotePropertyValue $servers",
    "      return @{ root = $root; unsupported = (cxSorted $unsup); dropped = @($dropped) }",
    "    }",
  ];
}

/**
 * Step 4d (the bash twin's `codexStagingShellLines`): check the Codex home
 * once, then stage its instructions as `rules/codex-agents.md` and its user
 * skills under `skills/<name>`, and record a `prompts/` folder.
 */
export function codexStagingPowerShellLines(): string[] {
  const CRED = psq(ARCHIVE_CREDENTIAL_OMISSION_REASON);
  const UNCHK = psq(ARCHIVE_LINK_UNCHECKED_OMISSION_REASON);
  const LINK = psq(CODEX_LINK_OMISSION_REASON);
  const [ra, rb] = CODEX_RULE_ARCHIVE_PATH.split("/");
  return [
    ...codexReaderPowerShellLines(),
    "    # ---- Step 4d - #5169: the Codex home's instructions and skills (no step call) ----",
    "    # Why a path is refused before anything is read through it (the bash twin's",
    "    # physical_path check), or $null; the physical path is in $script:cxPhys.",
    "    function cxRefusal($p) {",
    "      $script:cxPhys = physicalPath $p",
    `      if ($script:ppCred -or ($script:cxPhys -and (hasCredentialPart $script:cxPhys))) { return ${CRED} }`,
    `      if (-not $script:cxPhys) { return ${UNCHK} }`,
    "      return $null",
    "    }",
    "    if ($CODEX_FOUND) {",
    "      $xref = cxRefusal $CODEX_ROOT",
    `      if ($xref) { recordOmission ${psq(CODEX_HOME_SURFACE)} $xref } else { $CODEX_PHYS = $script:cxPhys; $CODEX_READ = $true }`,
    "    }",
    "    if ($CODEX_READ) {",
    "      # Instructions: the override when it holds a non-blank byte, else AGENTS.md.",
    "      $xi = $null",
    `      foreach ($xn in ${psArr(CODEX_INSTRUCTION_FILES)}) {`,
    "        $xf = Join-Path $CODEX_PHYS $xn",
    "        if (-not (Test-Path -LiteralPath $xf -PathType Leaf)) { continue }",
    "        $xit = Get-Item -LiteralPath $xf -Force",
    "        if ($xit.Attributes -band [IO.FileAttributes]::ReparsePoint) {",
    "          $xref = cxRefusal $xf",
    `          if ($xref) { recordOmission ${psq(CODEX_INSTRUCTIONS_SURFACE)} $xref; $xi = 'refused'; break }`,
    "          if (-not (Test-Path -LiteralPath $script:cxPhys -PathType Leaf)) { continue }",
    "          $xf = $script:cxPhys",
    "        }",
    "        # A file it cannot read is recorded and ends the search (as in bash).",
    "        try { $xbytes = [IO.File]::ReadAllBytes($xf) }",
    `        catch { recordOmission ${psq(CODEX_INSTRUCTIONS_SURFACE)} ${psq(CODEX_INSTRUCTIONS_UNREADABLE_REASON)}; $xi = 'refused'; break }`,
    "        $xblank = $true",
    "        foreach ($xb in $xbytes) { if (($xb -lt 9) -or (($xb -gt 13) -and ($xb -ne 32))) { $xblank = $false; break } }",
    "        if (-not $xblank) { $xi = $xf; break }",
    "      }",
    "      if ($xi -and ($xi -cne 'refused')) {",
    `        $xdst = Join-Path (Join-Path $STAGING ${psq(ra)}) ${psq(rb)}`,
    `        if (pathExists $xdst) { recordOmission ${psq(CODEX_INSTRUCTIONS_SURFACE)} ${psq(CODEX_RULE_SHADOWED_REASON)} }`,
    "        else {",
    "          try {",
    `            New-Item -ItemType Directory -Force -Path (Join-Path $STAGING ${psq(ra)}) | Out-Null`,
    "            Copy-Item -LiteralPath $xi -Destination $xdst -Force",
    `            $DIM_JSON[$DIMENSION_FIELD['rules']] = @($DIM_JSON[$DIMENSION_FIELD['rules']]) + @([ordered]@{ name = ${psq(CODEX_RULE_NAME)}; path = ${psq(CODEX_RULE_ARCHIVE_PATH)}; source = 'codex' })`,
    `          } catch { recordOmission ${psq(CODEX_INSTRUCTIONS_SURFACE)} 'instructions file could not be copied' }`,
    "        }",
    "      }",
    "      # Skills: ~/.agents/skills first, then the deprecated $CODEX_HOME/skills, in",
    "      # ordinal order; only a folder holding a SKILL.md file (not a link), no",
    "      # dot-names; a name already staged wins.",
    `      foreach ($xr in @((Join-Path $HOME_DIR ${psq(CODEX_AGENTS_SKILLS_DIR)}), (Join-Path $CODEX_PHYS 'skills'))) {`,
    "        if (-not (Test-Path -LiteralPath $xr -PathType Container)) { continue }",
    "        $xref = cxRefusal $xr",
    `        if ($xref) { recordOmission ${psq(CODEX_SKILLS_SURFACE)} $xref; continue }`,
    "        $xrp = $script:cxPhys",
    "        # A folder it cannot list is recorded, never read as empty (as in bash).",
    "        try { $xkids = [string[]]@((New-Object IO.DirectoryInfo $xrp).EnumerateFileSystemInfos() | ForEach-Object { $_.Name }) }",
    `        catch { recordOmission ${psq(CODEX_SKILLS_SURFACE)} ${psq(CODEX_SKILLS_UNREADABLE_REASON)}; continue }`,
    "        [Array]::Sort($xkids, [StringComparer]::Ordinal)",
    "        foreach ($xs in $xkids) {",
    "          if ($xs.StartsWith('.')) { continue }",
    `          if ($xs.Contains("\`n") -or $xs.Contains('\\')) { recordOmission ${psq(CODEX_SKILLS_SURFACE)} ${UNCHK}; continue }`,
    "          $xc = [IO.Path]::Combine($xrp, $xs)",
    "          $xa = (New-Object IO.FileInfo $xc).Attributes",
    "          if ([int]$xa -eq -1) { continue }",
    `          if ($xa -band [IO.FileAttributes]::ReparsePoint) { recordOmission (${psq(CODEX_SKILLS_SURFACE_PREFIX)} + $xs) ${LINK}; continue }`,
    "          if (-not ($xa -band [IO.FileAttributes]::Directory)) { continue }",
    "          $xsa = (New-Object IO.FileInfo ([IO.Path]::Combine($xc, 'SKILL.md'))).Attributes",
    "          if (([int]$xsa -eq -1) -or ($xsa -band [IO.FileAttributes]::Directory) -or ($xsa -band [IO.FileAttributes]::ReparsePoint)) { continue }",
    `          if (hasCredentialPart ($xrp + '/' + $xs)) { recordOmission (${psq(CODEX_SKILLS_SURFACE_PREFIX)} + $xs) ${CRED}; continue }`,
    "          $xdst = Join-Path (Join-Path $STAGING 'skills') $xs",
    `          if (pathExists $xdst) { recordOmission (${psq(CODEX_SKILLS_SURFACE_PREFIX)} + $xs) ${psq(CODEX_SKILL_SHADOWED_REASON)}; continue }`,
    "          if (-not (copyTreeExcluding $xc $xdst)) { throw ('tar failed collecting the Codex skill ' + $xs) }",
    "          # A link inside is removed and recorded (in ordinal order), never followed.",
    "          $xlinks = New-Object 'System.Collections.Generic.Dictionary[string,System.IO.FileSystemInfo]' ([StringComparer]::Ordinal)",
    "          $xpend = New-Object 'System.Collections.Generic.Queue[object]'",
    "          $xpend.Enqueue((New-Object IO.DirectoryInfo ([IO.Path]::Combine([IO.Path]::Combine($STG_FULL, 'skills'), $xs))))",
    "          while ($xpend.Count -gt 0) {",
    "            foreach ($e in (stagedChildren $xpend.Dequeue())) {",
    "              if ($e.Attributes -band [IO.FileAttributes]::ReparsePoint) { $xlinks[(stagedRel $e.FullName)] = $e }",
    "              elseif ($e -is [IO.DirectoryInfo]) { $xpend.Enqueue($e) }",
    "            }",
    "          }",
    "          $xrels = [string[]]@($xlinks.get_Keys())",
    "          [Array]::Sort($xrels, [StringComparer]::Ordinal)",
    "          foreach ($xl in $xrels) {",
    "            $xsurf = if ($xl.Contains(\"`n\")) { 'skills/' + $xs } else { $xl }",
    `            recordOmission $xsurf ${LINK}`,
    "            removeStaged $xlinks[$xl]",
    "          }",
    "          pruneCredentialNames ('skills/' + $xs)",
    "          $DIM_JSON[$DIMENSION_FIELD['skills']] = @($DIM_JSON[$DIMENSION_FIELD['skills']]) + @([ordered]@{ name = $xs; path = ('skills/' + $xs); source = 'codex' })",
    "        }",
    "      }",
    "      # D6: Codex has no custom prompts any more; a prompts/ folder is not carried.",
    `      if (Test-Path -LiteralPath (Join-Path $CODEX_PHYS 'prompts') -PathType Container) { recordOmission ${psq(CODEX_PROMPTS_SURFACE)} ${psq(CODEX_PROMPTS_OMISSION_REASON)} }`,
    "    }",
  ];
}

/**
 * Step 5 (the bash twin's `codexMcpShellLines`): read `config.toml` through
 * `cxReadToml` (never copied) and project it with `extractMcp $root 'codex'`.
 * Sets `$CODEX_MCP`.
 */
export function codexMcpPowerShellLines(): string[] {
  const [ua, ub] = CODEX_SERVER_UNSUPPORTED_PARTS;
  const [da, db] = CODEX_SERVER_DROPPED_PARTS;
  const S = psq(CODEX_CONFIG_SURFACE);
  return [
    "    # Codex - $CODEX_HOME/config.toml through the TOML subset reader (never copied).",
    "    $CODEX_MCP = @()",
    "    if ($CODEX_READ -and (Test-Path -LiteralPath (Join-Path $CODEX_PHYS 'config.toml') -PathType Leaf)) {",
    "      $cxf = Join-Path $CODEX_PHYS 'config.toml'",
    "      $cxref = linkRootRefusal $cxf",
    `      if ($cxref) { recordOmission ${S} $cxref }`,
    "      else {",
    "        $cx = $null",
    "        try { $cx = cxReadToml $cxf } catch { $cx = $null }",
    `        if ($null -eq $cx) { recordOmission ${S} ${psq(CODEX_TOML_UNREADABLE_REASON)} }`,
    "        else {",
    `          foreach ($n in $cx.unsupported) { recordOmission ${S} (${psq(ua)} + $n + ${psq(ub)}) }`,
    `          foreach ($dr in $cx.dropped) { recordOmission ${S} (${psq(da)} + $dr[0] + ${psq(db)} + ($dr[1] -join ', ')) }`,
    "          $CODEX_MCP = @(extractMcp $cx.root 'codex')",
    "        }",
    "      }",
    "    }",
  ];
}
