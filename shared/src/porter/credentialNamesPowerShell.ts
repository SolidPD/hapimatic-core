/**
 * Configuration Porter — the PowerShell credential-name prune
 * (`pruneCredentialNames`), the twin of the bash `prune_credential_names` in
 * `credentialNamesShell.ts` (issue #4172), pinned to the same result by the
 * #3447 equivalence harness. A sibling of `exportScriptPowerShell.ts` so that
 * file stays under its line budget (epic #4290 T25; the
 * `settingsScriptPowerShell.ts` precedent, #4173).
 *
 * The lines run inside the PowerShell exporter's main block and rely on its
 * helpers and state: `recordOmission`, `stagedChildren`, `stagedRel`,
 * `removeStaged`, `makeOwnerWritable`, `$ON_WINDOWS`, `$STAGING` and `$STG_FULL`.
 *
 * NODE-FREE (R7): string builders only.
 */
import {
  ARCHIVE_CREDENTIAL_OMISSION_REASON,
  ARCHIVE_LINK_UNCHECKED_OMISSION_REASON,
  psq,
} from "./exportShared";
import {
  ARCHIVE_CREDENTIAL_NAMES,
  ARCHIVE_CREDENTIAL_PREFIXES,
} from "./manifest";

/** A PowerShell array literal `@('a', 'b', …)` from string elements. */
function psArray(items: readonly string[]): string {
  return `@(${items.map(psq).join(", ")})`;
}

/**
 * `$CREDENTIAL_NAMES`, `$CREDENTIAL_PREFIXES`, `isCredentialName` and
 * `pruneCredentialNames <sub>`, which removes every credential-named file or
 * folder under `$STAGING/<sub>` and records one omission per removed path.
 */
export function credentialNamesPowerShellLines(): string[] {
  return [
    "    # #4172: the prune_credential_names twin. Removes every file or folder under",
    "    # $STAGING/<sub> whose name (any case) is credential-bearing, at its first",
    "    # matching ancestor, and records one omission per removed path in ordinal",
    "    # order (Sort-Object is culture-aware and case-insensitive; the bash twin",
    "    # sorts LC_ALL=C). The walk never descends a link, and a matching link is",
    "    # removed as a link (a recursive Remove-Item can delete through one).",
    `    $CREDENTIAL_NAMES = ${psArray(ARCHIVE_CREDENTIAL_NAMES)}`,
    `    $CREDENTIAL_PREFIXES = ${psArray(ARCHIVE_CREDENTIAL_PREFIXES)}`,
    "    function isCredentialName($name) {",
    "      if ($CREDENTIAL_NAMES -ccontains $name.ToLowerInvariant()) { return $true }",
    "      foreach ($pre in $CREDENTIAL_PREFIXES) {",
    "        if ($name.StartsWith($pre, [StringComparison]::OrdinalIgnoreCase)) { return $true }",
    "      }",
    "      return $false",
    "    }",
    "    function pruneCredentialNames($sub) {",
    "      $root = Join-Path $STAGING $sub",
    "      if (-not (Test-Path -LiteralPath $root -PathType Container)) { return }",
    "      $found = New-Object 'System.Collections.Generic.Dictionary[string,System.IO.FileSystemInfo]' ([StringComparer]::Ordinal)",
    "      $pending = New-Object 'System.Collections.Generic.Queue[object]'",
    "      $pending.Enqueue((New-Object IO.DirectoryInfo ([IO.Path]::Combine($STG_FULL, $sub))))",
    "      while ($pending.Count -gt 0) {",
    "        foreach ($e in (stagedChildren $pending.Dequeue())) {",
    "          $isLink = [bool]($e.Attributes -band [IO.FileAttributes]::ReparsePoint)",
    "          if (isCredentialName $e.Name) {",
    "            $found[(stagedRel $e.FullName)] = $e",
    "          } elseif (($e -is [IO.DirectoryInfo]) -and -not $isLink) {",
    "            $pending.Enqueue($e)",
    "          }",
    "        }",
    "      }",
    "      $rels = [string[]]@($found.Keys)",
    "      [Array]::Sort($rels, [StringComparer]::Ordinal)",
    "      foreach ($rel in $rels) {",
    "        $e = $found[$rel]",
    `        recordOmission $rel '${ARCHIVE_CREDENTIAL_OMISSION_REASON}'`,
    "        # #4328: off Windows, the remove_credential_paths widen: the parent, then the",
    "        # item unless a link (on Windows removeStaged's forced delete handles ReadOnly).",
    "        if (-not $ON_WINDOWS) { & chmod u+w -- ([IO.Path]::GetDirectoryName($e.FullName)) 2>$null }",
    "        if (-not ($e.Attributes -band [IO.FileAttributes]::ReparsePoint)) { makeOwnerWritable $e.FullName }",
    "        removeStaged $e",
    "      }",
    "    }",
  ];
}

/**
 * The link checks the PowerShell exporter's link materialization and hook
 * registration use (issue #4172, OOS-6): `physicalPath`, `hasCredentialPart`,
 * `pathExists`, `credentialLinks`, `underLink` and `linkRootRefusal`, the twins
 * of the bash `physical_path`, `has_credential_part`, `credential_links` and
 * `under_link` in `credentialNamesShell.ts`, plus `reparseTag` and
 * `isCloudPlaceholder` (#4321, ruling O2). Moved here from
 * `exportScriptPowerShell.ts` (#4321, epic #4290 T25); #4321 then added the
 * O2 placeholder rule and the loop (`l`) lines. They rely on `isCredentialName`
 * (above) and on the main block's `$ON_WINDOWS`, `$STAGING` and `$STG_FULL`.
 */
export function linkCheckPowerShellLines(): string[] {
  return [
    "    # #4172 (OOS-6): the bash twin's physical_path / has_credential_part /",
    "    # credential_links. A link whose physical target has a credential-bearing",
    "    # part (skills/keys -> ~/.aws) is refused, at any depth -h would follow,",
    "    # except through the gap tracked in #4332: off Windows a backslash in a",
    "    # link's target text is read as a folder separator.",
    "    # #4321 (O2): the reparse tag of $p from fsutil (its first 0x value, the",
    "    # same in every display language), or 0 when it cannot be read, which",
    "    # keeps the path refused.",
    "    function reparseTag($p) {",
    "      try {",
    "        $rq = (& fsutil.exe reparsepoint query $p 2>$null | Out-String)",
    "        if ($LASTEXITCODE -ne 0) { return [uint32]0 }",
    "        $rm = [regex]::Match($rq, '0x([0-9a-fA-F]{8})')",
    "        if (-not $rm.Success) { return [uint32]0 }",
    "        return [Convert]::ToUInt32($rm.Groups[1].Value, 16)",
    "      } catch { return [uint32]0 }",
    "    }",
    "    # True for a cloud-files placeholder: IO_REPARSE_TAG_CLOUD (0x9000001A)",
    "    # once its sub-type bits (0x0000F000) are masked off.",
    "    function isCloudPlaceholder($p) {",
    "      return (((reparseTag $p) -band [Convert]::ToUInt32('FFFF0FFF', 16)) -eq [Convert]::ToUInt32('9000001A', 16))",
    "    }",
    "    # physicalPath resolves every link along the path by hand (.Target works",
    "    # on 5.1 and 7; ResolveLinkTarget is .NET 6+ only), or returns $null.",
    "    # It walks the path one part at a time. The path it is given is read the",
    "    # way this script's own reads (Test-Path, Copy-Item) read it: by their own",
    "    # resolver (GetUnresolvedProviderPathFromPSPath): '~' and a FileSystem",
    "    # drive (temp:), a relative path from the current location, and any '..'",
    "    # as text; then off Windows every backslash as a separator (turned into",
    "    # '/' after the resolver, which keeps a leading two-backslash path as given",
    "    # and reads a module-qualified provider name with its backslash), so it",
    "    # checks the same file the copy takes. A path the resolver",
    "    # cannot read (an unknown drive such as x:y, or '::' after the first",
    "    # character), one on another provider (Env:), or one GetFullPath rejects",
    "    # returns $null. A '..' inside a link's target is",
    "    # taken after that link is resolved (as Linux and macOS do; Windows is",
    "    # unverified, #4332), except that off Windows a backslash in a target is",
    "    # read as a separator (a backslash-spelled '..' included), which the",
    "    # kernel reads as part of a name (the #4332 gap). It sets",
    "    # $script:ppCred when a link it follows has a credential-bearing part in",
    "    # its name or its target, even when the physical path no longer shows one",
    "    # (~/.ssh -> ~/Dropbox/keys), and $script:ppProc (returning $null) when the",
    "    # walk reaches /proc; a caller that needs them must read them right after",
    "    # its call, since the next call resets both.",
    "    function physicalPath($p) {",
    "      $script:ppCred = $false",
    "      $script:ppProc = $false",
    "      $pinfo = $null; $pdrive = $null",
    "      try { $p = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($p, [ref]$pinfo, [ref]$pdrive) } catch { return $null }",
    "      if ($pinfo.Name -ne 'FileSystem') { return $null }",
    "      if (-not $ON_WINDOWS) { $p = $p.Replace('\\', '/') }",
    "      try { $p = [IO.Path]::GetFullPath($p) } catch { return $null }",
    "      $root = [IO.Path]::GetPathRoot($p)",
    "      $todo = New-Object 'System.Collections.Generic.List[string]'",
    "      $todo.AddRange([string[]]@($p.Substring($root.Length).Split([char[]]@('/', '\\'), [StringSplitOptions]::RemoveEmptyEntries)))",
    "      $cur = $root",
    "      $hops = 0",
    "      while ($todo.Count -gt 0) {",
    "        $part = $todo[0]",
    "        $todo.RemoveAt(0)",
    "        if ($part -eq '.') { continue }",
    "        if ($part -eq '..') {",
    "          # GetDirectoryName: Split-Path -Parent returns '' for a top-level",
    "          # folder off Windows (the walk stayed below '/') and throws for '/'.",
    "          $up = [IO.Path]::GetDirectoryName($cur)",
    "          if ($up) { $cur = $up }",
    "          continue",
    "        }",
    "        $next = Join-Path $cur $part",
    "        # A walk into /proc is unchecked ($script:ppProc): read here, /proc/self is",
    "        # this process, never the tar that copies. -eq ignores case, so /PROC is",
    "        # refused too (fail-closed; the bash twin's case is case-sensitive).",
    "        if (($next -eq '/proc') -or $next.StartsWith('/proc/')) { $script:ppProc = $true; return $null }",
    "        $it = Get-Item -LiteralPath $next -Force -ErrorAction SilentlyContinue",
    "        if (-not $it) { return $null }",
    "        if ($it.Attributes -band [IO.FileAttributes]::ReparsePoint) {",
    "          $hops++",
    "          if ($hops -gt 40) { return $null }",
    "          $tg = @($it.Target)[0]",
    "          if (-not $tg) {",
    "            # #4321 (ruling O2): a cloud-files placeholder (a OneDrive-synced",
    "            # ~/.claude) is a reparse point with no link target: walk it as a",
    "            # plain folder. Any other target-less reparse point is unchecked.",
    "            if ($ON_WINDOWS -and (isCloudPlaceholder $next)) { $hops--; $cur = $next; continue }",
    "            return $null",
    "          }",
    "          if (hasCredentialPart ($part + '/' + $tg)) { $script:ppCred = $true }",
    "          $troot = [IO.Path]::GetPathRoot($tg)",
    "          if ($troot) { $cur = $troot }",
    "          $todo.InsertRange(0, [string[]]@($tg.Substring($troot.Length).Split([char[]]@('/', '\\'), [StringSplitOptions]::RemoveEmptyEntries)))",
    "        } else {",
    "          $cur = $next",
    "        }",
    "      }",
    "      return $cur",
    "    }",
    "    function hasCredentialPart($path) {",
    "      foreach ($part in $path.Split([char[]]@('/', '\\'), [StringSplitOptions]::RemoveEmptyEntries)) {",
    "        if (isCredentialName $part) { return $true }",
    "      }",
    "      return $false",
    "    }",
    "    # True when $p names an existing file or folder; off Windows also for a",
    "    # link whose target is missing (File.Exists, like Test-Path there, is true",
    "    # for a dangling link). Off Windows by .NET: the path cmdlets read '::' in",
    "    # a path as a provider qualifier, even with -LiteralPath, and report it",
    "    # missing.",
    "    function pathExists($p) {",
    "      if ($ON_WINDOWS) { return (Test-Path -LiteralPath $p) }",
    "      return ([IO.Directory]::Exists($p) -or [IO.File]::Exists($p))",
    "    }",
    "    # One 'c<TAB>path' per link under $dir whose physical target has a",
    "    # credential-bearing part; one 'u<TAB>path' per link it could not check",
    "    # (its target does not resolve, it is more than 40 folder links deep, the",
    "    # walk reaches /proc, or off Windows a part of its path or target holds",
    "    # '::') and per folder it cannot list (off Windows, a '::' in its path);",
    "    # and off Windows one 'b<TAB>path' per entry whose name holds a backslash",
    "    # (a path string with it would name another path; it is neither descended",
    "    # nor checked). It follows folder links as -h does, along every path (a",
    "    # folder two links reach is checked under both), stops only at a folder",
    "    # already on the current path or one that holds the link (a loop: loop ->",
    "    # . or up -> ..), writing one 'l<TAB>path' for that link, which the copy",
    "    # leaves out (#4321), and only reads.",
    "    function credentialLinks($dir, $prefix) {",
    "      $out = New-Object 'System.Collections.Generic.List[string]'",
    "      $tab = [string][char]9",
    "      $queue = New-Object 'System.Collections.Generic.Queue[object]'",
    "      $psep = [string][IO.Path]::DirectorySeparatorChar",
    "      $pcmp = if ($ON_WINDOWS) { [StringComparison]::OrdinalIgnoreCase } else { [StringComparison]::Ordinal }",
    '      $queue.Enqueue(@($dir, $prefix, 0, ("`n" + (physicalPath $dir) + "`n")))',
    "      while ($queue.Count -gt 0) {",
    "        $q = $queue.Dequeue()",
    "        # A folder it cannot list is refused whole as unchecked, since tar -h",
    "        # would copy what the check never saw (off Windows, a '::' in its path",
    "        # makes Get-ChildItem fail, and the links below it would ship).",
    "        $cle = $null",
    "        $kids = @(Get-ChildItem -LiteralPath $q[0] -Force -ErrorAction SilentlyContinue -ErrorVariable cle)",
    "        if (@($cle).Count -gt 0) { $out.Add('u' + $tab + $q[1]); continue }",
    "        foreach ($e in $kids) {",
    "          $rel = $q[1] + '/' + $e.Name",
    "          if ((-not $ON_WINDOWS) -and $e.Name.Contains('\\')) { $out.Add('b' + $tab + $rel); continue }",
    "          if ($e.Attributes -band [IO.FileAttributes]::ReparsePoint) {",
    "            $phys = physicalPath $e.FullName",
    "            if ($script:ppCred) { $out.Add('c' + $tab + $rel); continue }",
    "            if (-not $phys) {",
    "              if ($script:ppProc -or (pathExists $e.FullName)) { $out.Add('u' + $tab + $rel) }",
    "              continue",
    "            }",
    "            if (hasCredentialPart $phys) { $out.Add('c' + $tab + $rel); continue }",
    "            if (-not (Test-Path -LiteralPath $phys -PathType Container)) { continue }",
    '            $ploop = $q[3].Contains("`n" + $phys + "`n")',
    "            $ppar = physicalPath ([IO.Path]::GetDirectoryName($e.FullName))",
    "            if ($ppar -and ($ppar + $psep).StartsWith($phys.TrimEnd($psep) + $psep, $pcmp)) { $ploop = $true }",
    "            if ($ploop) { $out.Add('l' + $tab + $rel); continue }",
    "            if ($q[2] -ge 40) { $out.Add('u' + $tab + $rel); continue }",
    '            $queue.Enqueue(@($phys, $rel, ($q[2] + 1), ($q[3] + $phys + "`n")))',
    "          } elseif ($e.PSIsContainer) {",
    "            $queue.Enqueue(@($e.FullName, $rel, $q[2], $q[3]))",
    "          }",
    "        }",
    "      }",
    "      return ,$out.ToArray()",
    "    }",
    "    # True when a folder between $STAGING and $rel is a link: a path below a",
    "    # staged link is not the export's copy, and removing it would remove",
    "    # through the link, into the folder the link names.",
    "    function underLink($rel) {",
    "      if (-not $ON_WINDOWS) {",
    "        # By .NET: a backslash in a name stays in that name.",
    "        $parts = $rel.Split([char[]]@('/'), [StringSplitOptions]::RemoveEmptyEntries)",
    "        $p = $STG_FULL",
    "        for ($i = 0; $i -lt $parts.Length - 1; $i++) {",
    "          $p = [IO.Path]::Combine($p, $parts[$i])",
    "          $a = (New-Object IO.FileInfo $p).Attributes",
    "          if (([int]$a -ne -1) -and ($a -band [IO.FileAttributes]::ReparsePoint)) { return $true }",
    "        }",
    "        return $false",
    "      }",
    "      $parts = $rel.Split([char[]]@('/', '\\'), [StringSplitOptions]::RemoveEmptyEntries)",
    "      $p = $STAGING",
    "      for ($i = 0; $i -lt $parts.Length - 1; $i++) {",
    "        $p = Join-Path $p $parts[$i]",
    "        $it = Get-Item -LiteralPath $p -Force -ErrorAction SilentlyContinue",
    "        if ($it -and ($it.Attributes -band [IO.FileAttributes]::ReparsePoint)) { return $true }",
    "      }",
    "      return $false",
    "    }",
    "    # #4172 (OOS-6): why a source folder that is itself a link is refused before",
    "    # its tree is copied, or $null (no link, or its target passes). The copy",
    "    # (tar -C) follows that link, so the materialize pass never sees it: its",
    "    # credential and unchecked checks for a staged link run here first (a",
    "    # caller has already seen a folder there, so it is never dangling).",
    "    function linkRootRefusal($src) {",
    "      $it = Get-Item -LiteralPath $src -Force -ErrorAction SilentlyContinue",
    "      if (-not $it -or -not ($it.Attributes -band [IO.FileAttributes]::ReparsePoint)) { return $null }",
    "      $phys = physicalPath $src",
    `      if ($script:ppCred) { return '${ARCHIVE_CREDENTIAL_OMISSION_REASON}' }`,
    `      if (-not $phys) { return '${ARCHIVE_LINK_UNCHECKED_OMISSION_REASON}' }`,
    `      if (hasCredentialPart $phys) { return '${ARCHIVE_CREDENTIAL_OMISSION_REASON}' }`,
    "      return $null",
    "    }",
  ];
}
